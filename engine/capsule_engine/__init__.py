#!/usr/bin/env python3
"""capsule_engine — vanilla-Python core of the Sovereign Agency OS.

A lightweight, modular state-machine orchestrator that uses the file system
as its database. Every job is a **Deliverable Capsule**: a directory holding
``manifest.json`` (the state tracker) and its artifacts (any relative file,
``copy.md`` by default — the bound path is recorded per capsule).

Zero external dependencies — standard library only (Python 3.10+).

Components:
- :class:`capsule_engine.worker.BaseWorker` — abstract worker contract with
  safe capsule I/O helpers, token accounting, and a lock-wrapped ``run()``
  entry point;
- :class:`capsule_engine.locking.CapsuleLock` — crash-safe ``.lock`` file
  mutual exclusion for overlapping cron pulses;
- :class:`capsule_engine.router.CapsuleRouter` — reads an unlocked manifest
  and decides the next action (execute / hold / quarantine / missing);
- :mod:`capsule_engine.governance` — the dynamic autonomy ladder over a
  local ``governance.json`` (L0 human audit -> L2/L3 verified auto-approval);
- :mod:`capsule_engine.capabilities` — signed capability keys: authority by
  grant, verified offline and fail-closed, with branch-scoped grants
  (``capsule:approve:marketing``) replacing the omnipotent shared token;
- :mod:`capsule_engine.manifest` — the state machine, the TOCTOU SHA-256
  artifact binding, and token usage accumulation.

Typical pulse loop — one pass routes every capsule and runs the matching
worker from the explicit ``workers.WORKERS`` registry (see
``orchestration/capsule_pulse.py`` for the executable loop)::

    from orchestration.capsule_pulse import run_pulse
    run_pulse(capsules_root)
"""

